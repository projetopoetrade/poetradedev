/**
 * Generates the WEAPON_BASE_STATS table from the poewiki.net Cargo API.
 *
 * Usage:
 *   node scripts/generate-weapon-bases.mjs
 *
 * The script prints a TypeScript const block to stdout that can be pasted
 * directly into lib/pob-parser.ts to replace the WEAPON_BASE_STATS constant.
 *
 * Source: https://www.poewiki.net/wiki/Special:CargoTables/weapons
 * Fields: physical_damage_min, physical_damage_max, critical_strike_chance, attack_speed
 * Filter: rarity='Normal' AND physical_damage_min IS NOT NULL
 */

const CARGO_URL = new URL('https://www.poewiki.net/w/api.php');
CARGO_URL.searchParams.set('action', 'cargoquery');
CARGO_URL.searchParams.set('tables', 'weapons,items');
CARGO_URL.searchParams.set('join on', 'weapons._pageName=items._pageName');
CARGO_URL.searchParams.set(
  'fields',
  'weapons._pageName=name,weapons.physical_damage_min,weapons.physical_damage_max,weapons.critical_strike_chance,weapons.attack_speed',
);
CARGO_URL.searchParams.set(
  'where',
  "weapons.physical_damage_min IS NOT NULL AND items.rarity='Normal'",
);
CARGO_URL.searchParams.set('limit', '500');
CARGO_URL.searchParams.set('offset', '0');
CARGO_URL.searchParams.set('format', 'json');

async function fetchWeaponBases() {
  process.stderr.write('Fetching weapon base stats from poewiki.net Cargo API...\n');

  const resp = await fetch(CARGO_URL.toString());
  if (!resp.ok) {
    throw new Error(`HTTP ${resp.status}: ${resp.statusText}`);
  }

  const json = await resp.json();

  if (json.error) {
    throw new Error(`Cargo API error: ${json.error.info}`);
  }

  const rows = json.cargoquery ?? [];
  process.stderr.write(`Fetched ${rows.length} weapon base types.\n`);

  // Sort alphabetically for readability
  rows.sort((a, b) => a.title.name.localeCompare(b.title.name));

  // Build the TypeScript const block
  const lines = [
    '// ─── Weapon base type stats ─────────────────────────────────────────────────',
    '// Source: poewiki.net Cargo API (weapons table, rarity=Normal)',
    '// Generated by: node scripts/generate-weapon-bases.mjs',
    `// Generated at: ${new Date().toISOString()}`,
    '// ─────────────────────────────────────────────────────────────────────────────',
    'const WEAPON_BASE_STATS: Record<string, { phys: [number, number]; aps: number; crit: number }> = {',
  ];

  for (const row of rows) {
    const { name } = row.title;
    const min = parseInt(row.title['physical damage min'], 10);
    const max = parseInt(row.title['physical damage max'], 10);
    const crit = parseFloat(row.title['critical strike chance']);
    const aps = parseFloat(row.title['attack speed']);

    if (isNaN(min) || isNaN(max) || isNaN(crit) || isNaN(aps)) {
      process.stderr.write(`  Skipping "${name}" — missing values: min=${min} max=${max} crit=${crit} aps=${aps}\n`);
      continue;
    }

    // Escape any special characters in the name for use as a TypeScript key
    const key = name.replace(/"/g, '\\"');
    lines.push(`  "${key}": { phys: [${min}, ${max}], aps: ${aps}, crit: ${crit} },`);
  }

  lines.push('};');
  lines.push('');

  return lines.join('\n');
}

fetchWeaponBases()
  .then((output) => {
    process.stdout.write(output);
    process.stderr.write('Done.\n');
  })
  .catch((err) => {
    process.stderr.write(`Error: ${err.message}\n`);
    process.exit(1);
  });
